class RunCompletionMixin(RegistryState):
    @staticmethod
    def _round_result(event: dict[str, Any]) -> dict[str, Any] | None:
        return validate_round_result(event)

    @staticmethod
    def _assignment_reports_round_result(
        assignments: list[dict[str, Any]], index: int
    ) -> bool:
        """Only the last writable member may publish the aggregate verdict."""
        return assignment_reports_round_result(assignments, index)

    def _record_generated_workspace_artifacts(
        self,
        sandbox: dict[str, Any],
        run_request: dict[str, Any],
        event: dict[str, Any],
        artifact_snapshot: dict[str, Any] | None,
        assignment: dict[str, Any] | None = None,
    ) -> None:
        """Index the files a run reported, each once per run.

        The per-run dedupe below makes this safe to call twice for one event:
        the terminal handler indexes before it takes the global dispatch lock
        (``_index_generated_files_before_finalization``), and the finalization
        under that lock finds nothing left to upload. A retried finalization
        fills in only what an earlier attempt did not index.
        """
        session_id = run_request["sessionId"]
        # Layout and the per-run dedupe read snapshot fields only.
        session = self.store.get_session_header(session_id)
        workspace_path = sandbox.get("workspacePath")
        artifact_workspace_path = workspace_path
        if (
            workspace_path
            and session.get("workspaceLayout") == "thread"
            and has_capability(sandbox, DAEMON_CAPABILITY_THREAD_WORKSPACES)
        ):
            artifact_workspace_path = str(Path(workspace_path) / session_id)
        elif (
            workspace_path
            and session.get("workspaceLayout") in ("project", "task")
            and isinstance(session.get("workspaceSubpath"), str)
            and session["workspaceSubpath"]
            and has_capability(
                sandbox,
                DAEMON_CAPABILITY_PROJECT_WORKSPACES
                if session.get("workspaceLayout") == "project"
                else DAEMON_CAPABILITY_TASK_WORKSPACES,
            )
        ):
            artifact_workspace_path = (
                self._linked_workspace_path(session)
                if session["workspaceSubpath"].startswith(LINKED_WORKSPACE_PREFIX)
                else _confined_workspace_path(
                    workspace_path, session["workspaceSubpath"]
                )
            ) or workspace_path
        if isinstance(event.get("generatedFiles"), list):
            items = daemon_reported_generated_files(
                artifact_workspace_path,
                event["generatedFiles"],
                produced_files=has_capability(sandbox, DAEMON_CAPABILITY_PRODUCED_FILES),
            )
        else:
            # Older daemons must upgrade to report generated files; a host
            # filesystem walk could disclose unrelated backend files.
            items = []
        # A file may legitimately be re-generated by a later run; each change
        # gets its own artifact attributed to the run that produced it. Only
        # duplicates within one report are dropped.
        seen_relative_paths = {
            artifact.get("workspaceRelativePath")
            for artifact in session.get("artifacts", [])
            if artifact.get("agentRunId") == event["runId"]
        }
        for item in items:
            path = item["path"]
            relative_path = item["relativePath"]
            if relative_path in seen_relative_paths:
                continue
            seen_relative_paths.add(relative_path)
            artifact = {
                "id": new_database_id(),
                "kind": "workspace_file",
                "title": item["title"],
                "path": path,
                "createdAt": now_iso(),
                "agentRunId": event["runId"],
                "bytes": item["bytes"],
                "contentType": item["contentType"],
                "workspaceRelativePath": item["relativePath"],
                **(
                    {"snapshotSkipped": item["snapshotSkipped"]}
                    if item.get("snapshotSkipped")
                    else {}
                ),
                **(
                    {"agentId": assignment["agentId"]}
                    if assignment and assignment.get("agentId")
                    else {}
                ),
            }
            if hasattr(self.store, "index_workspace_artifact"):
                artifact, _session = self.store.index_workspace_artifact(
                    session_id, artifact, item.get("content")
                )
            else:
                self.store.append_event(
                    session_id,
                    relay_event("artifact.created", session_id, {"artifact": artifact}),
                    hydrate_events=False,
                )
            logger.info(
                "Generated workspace artifact indexed",
                session_id=session_id,
                run_id=event["runId"],
                artifact_id=artifact["id"],
                path=item["relativePath"],
                snapshot=item.get("content") is not None,
            )

    def _closing_controller(self, run_request: dict[str, Any]) -> SessionController:
        """The controller that closes a round's thread and settles its task."""
        sandbox = self.sandboxes.get(run_request["nodeId"])
        if sandbox:
            return self._controller_for_sandbox(
                sandbox, run_request.get("taskId"), run_request
            )
        return SessionController(
            self.store,
            task_store=self.task_store,
            task_id=run_request.get("taskId"),
            task_execution_owner=request_execution_owner(run_request),
        )

    def _complete_run_request(self, run_request: dict[str, Any], outcome: str) -> None:
        controller = self._closing_controller(run_request)
        task_status = "done"
        round_result = (run_request.get("state") or {}).get(ROUND_RESULT_STATE_KEY)
        if isinstance(round_result, dict):
            task_status, outcome = self._round_outcome(
                round_result, task_status, outcome
            )
        else:
            self._note_missing_round_result(run_request, task_status)
            if self._round_result_was_required(run_request):
                task_status = "waiting_for_human"
                outcome = (
                    "The round ended without its required aggregate verdict. "
                    "Review the work before continuing or accepting it."
                )
        blockers = completion_blockers(
            run_request["assignments"], run_request.get("state") or {},
            require_evidence=bool((run_request.get("state") or {}).get(WORK_PROTOCOL)),
            allow_unfinished=isinstance(round_result, dict) and round_result.get("status") == "continue",
        )
        # An agent that stopped to ask is the one thing its human must answer.
        # Its own blocked report also trips the acceptance gate, but quoting
        # the gate instead would replace the question with bookkeeping; the
        # gate applies again to the round the answer resumes.
        asked = is_question(round_result)
        if blockers:
            task_status = "waiting_for_human"
            if not asked:
                outcome = WORK_NEEDS_ATTENTION + " " + " ".join(blockers)
        if isinstance(round_result, dict):
            self._record_round_result(run_request, {"status": "blocked", "note": outcome} if blockers and not asked else round_result, task_status)
        if task_status == "done" and self.task_store and run_request.get("taskId"):
            task_status = acceptance_status(
                self.task_store.get_task(run_request["taskId"]), task_status
            )
        work_outcome = {
            "waiting_for_human": "blocked",
            "assigned": "unfinished",
            "review": "needs_review",
        }.get(task_status, "reported_done" if (
            isinstance(round_result, dict)
            and round_result.get("status") == "done"
            and (run_request.get("state") or {}).get(WORK_PROTOCOL)
        ) else "unverified")
        participant_failures = (run_request.get("state") or {}).get(
            PARTICIPANT_FAILURES_STATE_KEY
        )
        if isinstance(participant_failures, list) and participant_failures:
            outcome = (
                f"{outcome} {len(participant_failures)} participant assignment(s) "
                "failed; inspect the thread before closing the work."
            )
        # The question rides on the completion as structured fields, so the
        # thread quotes it exactly and offers its answers as choices. Gate
        # reasons the question stood in front of travel as notes rather than
        # disappearing: the person answering should know about them.
        # Every park is a wait with an id an answer must name. The id derives
        # from the run so a retried finalization writes the same wait.
        input_request = (
            self._input_request(run_request, round_result, blockers, participant_failures)
            # is_question() already implies a dict verdict; restated for the checker.
            if asked and isinstance(round_result, dict)
            # A blocked verdict with no words still asked for help: it is the
            # agent's question, not a gate's check.
            else wait_record(
                "question" if outcome.startswith(BLOCKED_ROUND_PREAMBLE) else "check",
                question_id_for_run(run_request["id"]),
                unreported=self._round_unreported(
                    run_request, round_result, blockers, participant_failures
                ),
            )
        ) if task_status == "waiting_for_human" else None
        if (
            self.store.get_session(run_request["sessionId"]).get("status")
            != "completed"
        ):
            controller.complete_session(
                run_request["sessionId"], outcome, task_status=task_status,
                work_outcome=work_outcome, input_request=input_request,
                next_steps=(run_request.get("state") or {}).get(NEXT_STEPS_STATE_KEY),
            )
        else:
            # A retried finalization after a crash between the session write
            # and the task write: settle the task the thread already reports.
            controller.repair_completion(
                run_request["sessionId"], outcome, task_status=task_status,
                work_outcome=work_outcome, input_request=input_request,
            )
        self.daemon_store.update_run_request(
            run_request["id"], {"status": "completed", "error": None}
        )
        self.update_status(
            run_request["nodeId"], {"status": "ready", "lastError": None}
        )

    def _round_unreported(
        self,
        run_request: dict[str, Any],
        round_result: Any,
        blockers: list[str],
        participant_failures: Any,
    ) -> bool:
        """Whether the only thing wrong with this round is that no report
        reached Relay — so whatever the agent needs is in its last message.

        A verdict Relay refused was still filed, and a step that failed to run
        or a plan error left a reason worth quoting; neither is this case.
        """
        if isinstance(round_result, dict):
            return False
        state = run_request.get("state") or {}
        if state.get(ROUND_RESULT_REJECTED_STATE_KEY) in ROUND_RESULT_REJECTIONS:
            return False
        if isinstance(participant_failures, list) and participant_failures:
            return False
        if any(blocker != MISSING_REPORT_REASON for blocker in blockers):
            return False
        return self._round_result_was_required(run_request)

    @staticmethod
    def _input_request(
        run_request: dict[str, Any],
        round_result: dict[str, Any],
        blockers: list[str],
        participant_failures: Any,
    ) -> dict[str, Any]:
        """What a blocked round asked its human, ready for `session.completed`."""
        # A step's own blocked report restates the question; every other gate
        # reason is something the question would otherwise hide.
        asking = {
            unaccepted_work_reason(result)
            for result in ((run_request.get("state") or {}).get(WORK_RESULTS) or {}).values()
            if isinstance(result, dict) and result.get("status") == "blocked"
        }
        notes = [blocker for blocker in blockers if blocker not in asking]
        if isinstance(participant_failures, list) and participant_failures:
            notes.append(
                f"{len(participant_failures)} participant assignment(s) failed; "
                "inspect the thread before closing the work."
            )
        return wait_record(
            "question",
            question_id_for_run(run_request["id"]),
            question=round_result.get("note"),
            options=round_result.get("options") or [],
            notes=notes,
        )

    @staticmethod
    def _round_outcome(
        round_result: dict[str, Any], task_status: str, outcome: str
    ) -> tuple[str, str]:
        """Let the round's own verdict decide whether the task is finished.

        This is an agent claim; required-work gates and human acceptance policy
        still apply. An unfinished task round requests another bounded attempt,
        and a blocked round requires attention. Neither closes the task as done.
        """
        status = round_result.get("status")
        note = round_result.get("note")
        if status == "done":
            return task_status, outcome
        if status == "blocked":
            reason = BLOCKED_ROUND_PREAMBLE
            return "waiting_for_human", f"{reason} {note}" if note else reason
        reason = "The round reported it is unfinished and asked to continue."
        # "assigned" puts the task back in the scheduler's queue. The budget is
        # enforced there, at dispatch, rather than here: this side has no view
        # of org settings and should not grow one.
        return "assigned", f"{reason} {note}" if note else reason

    def _note_missing_round_result(
        self, run_request: dict[str, Any], task_status: str
    ) -> None:
        """Say so when a task round was asked for a verdict and gave none.

        Silently treating "the CLI exited 0" as "the work is finished" is the
        guess this contract removes. The caller parks capable task rounds for a
        person after recording this diagnostic activity.
        """
        task_id = run_request.get("taskId")
        node = self.sandboxes.get(run_request["nodeId"]) or {}
        if (
            not task_id
            or not self.task_store
            or task_status != "done"
            or not has_capability(node, DAEMON_CAPABILITY_ROUND_RESULT)
        ):
            return
        rejected = (run_request.get("state") or {}).get(ROUND_RESULT_REJECTED_STATE_KEY)
        message = (
            f"Closed out without a round verdict: the agent's {ROUND_RESULT_RELATIVE_PATH} "
            f"was rejected because {ROUND_RESULT_REJECTIONS[rejected]}."
            if rejected in ROUND_RESULT_REJECTIONS
            else "Closed out without a round verdict: the agent did not write "
            f"{ROUND_RESULT_RELATIVE_PATH}."
        )
        self.task_store.record_activity(
            task_id, message, execution_owner=request_execution_owner(run_request),
        )

    def _round_result_was_required(self, run_request: dict[str, Any]) -> bool:
        if (run_request.get("state") or {}).get(WORK_PROTOCOL):
            return any(
                self._assignment_reports_round_result(run_request["assignments"], index)
                for index in range(len(run_request["assignments"]))
            )
        if not run_request.get("taskId") or not self.task_store:
            return False
        node = self.sandboxes.get(run_request["nodeId"]) or {}
        if not has_capability(node, DAEMON_CAPABILITY_ROUND_RESULT):
            return False
        return bool(run_request.get("assignments"))

    def _record_round_result(
        self,
        run_request: dict[str, Any],
        round_result: dict[str, Any],
        task_status: str,
    ) -> None:
        """Record the verdict on the task, and what a continuation would need.

        The continuation session is the whole point: a later round has to run
        in this thread, because a thread workspace belongs to its session and a
        fresh one would start without any of the work already done.
        """
        task_id = run_request.get("taskId")
        if not task_id or not self.task_store:
            return
        if task_status != "assigned":
            self.task_store.record_round(
                task_id, round_result=round_result, clear_continuation=True,
                execution_owner=request_execution_owner(run_request),
            )
            return
        task = self.task_store.get_task(task_id)
        rounds_used = task.get("roundCount")
        # The budget bounds *unattended* continuation. A round a person started
        # by answering is attended: it opens a fresh budget, so "keep going"
        # after an exhausted budget buys more than the one round it ran.
        manifest = (run_request.get("state") or {}).get(COLLABORATION_MANIFEST_STATE_KEY) or {}
        human_started = is_human_started_round(manifest)
        self.task_store.record_round(
            task_id,
            round_result=round_result,
            round_count=(
                rounds_used + 1
                if not human_started
                and isinstance(rounds_used, int) and not isinstance(rounds_used, bool)
                else 1
            ),
            continuation_session_id=run_request["sessionId"],
            execution_owner=request_execution_owner(run_request),
        )
