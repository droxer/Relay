router = APIRouter()


def occurrence_file_records(ctx: AppContext, task: dict[str, Any], actor: Actor) -> list[dict[str, Any]]:
    ids = (task.get("occurrenceIds") or []) if task.get("isRoutine") else []
    return ctx.task_store.task_run_records(actor["userId"], ids, with_timing=False) if ids else []


def _rollup_position(cursor: str) -> tuple[datetime, str, int]:
    try:
        stamp, task_id, raw_sequence = cursor.split("|")
        timestamp = datetime.fromisoformat(stamp)
        sequence = int(raw_sequence)
        if timestamp.tzinfo is None or not 0 <= sequence <= 2**63 - 1:
            raise ValueError
        return timestamp.astimezone(UTC), str(UUID(task_id)), sequence
    except (ValueError, OverflowError) as error:
        raise HTTPException(400, "Invalid Automation events cursor.") from error


@router.get("/tasks/{task_id}/events")
def task_events(
    task_id: str,
    request: Request,
    ctx: AppContextDep,
    include: str | None = None,
    view: str | None = None,
    before: int | None = Query(default=None, ge=0, le=2**63 - 1),
    cursor: str | None = Query(default=None, max_length=140),
    limit: int = Query(default=25, ge=1, le=100),
) -> dict[str, Any]:
    """The task's event log — the run history behind its current state.

    `include=occurrences` additionally folds in the event logs of a routine's
    promoted occurrences, in chronological pages. Each event keeps its own
    `taskId`, so the caller can still tell the
    routine's own entries from an occurrence's. The default answer stays the
    task's own log verbatim — an event-sourced replay must never silently
    receive another task's events.
    """
    actor = request_actor(request, ctx.auth_store)
    if include == "occurrences":
        task = get_task_header_for_actor(ctx.task_store, task_id, actor)
        events, position = ctx.task_store.task_rollup_event_page(
            actor["userId"], task_id, include_occurrences=bool(task["isRoutine"]),
            limit=limit, before=_rollup_position(cursor) if cursor else None,
        )
        return {
            "events": events,
            "nextCursor": f"{position[0].isoformat()}|{position[1]}|{position[2]}" if position else None,
        }
    if view == "lifecycle":
        task = get_task_header_for_actor(ctx.task_store, task_id, actor)
        return {"events": ctx.task_store.task_lifecycle_events(task["id"])}
    if view == "activity":
        task = get_task_header_for_actor(ctx.task_store, task_id, actor)
        try:
            return ctx.task_store.task_activity_page(task["id"], limit=limit, before=before)
        except ValueError as error:
            raise HTTPException(400, str(error)) from error
    task = get_task_for_actor(ctx.task_store, task_id, actor)
    return {"events": task["events"]}


def newest_artifacts_by_file(
    ctx: Any, sources: list[tuple[str, str]], *, owner_user_id: str | None, all_versions: bool = False,
    artifact_sessions: dict[str, dict[str, Any]] | None = None,
) -> dict[str, dict[str, Any]]:
    """Workspace artifacts across `(taskId, sessionId)` pairs, newest per file.

    A file regenerated by a later run must surface once, at its latest state,
    attributed to the run that produced that state. Every surface that counts
    or lists a task's generated files goes through here so the ledger's counts
    and the artifact list can never disagree.
    """
    if not sources:
        return {}
    if artifact_sessions is None:
        artifact_sessions = ctx.session_store.list_artifact_sources({key for _, key in sources}, owner_user_id)
    newest: dict[str, dict[str, Any]] = {}
    for origin_task_id, session_id in sources:
        session = artifact_sessions.get(session_id)
        if not session or session.get("ownerUserId") != owner_user_id:
            continue
        for artifact in workspace_artifacts(session):
            # Continuity checkpoints are retained artifacts too, but they are
            # not deliverables in the task/automation Files view or run count.
            if is_thread_record_artifact(session, artifact):
                continue
            key = (
                f"{session_id}:{artifact['id']}"
                if all_versions
                else workspace_artifact_key(session, artifact)
            )
            current = newest.get(key)
            if current is None or (artifact.get("createdAt") or "") >= (
                current.get("createdAt") or ""
            ):
                newest[key] = {
                    **artifact_index_item(session, artifact),
                    "taskId": origin_task_id,
                }
    return newest


@router.get("/tasks/{task_id}/artifacts")
def task_artifacts(
    task_id: str, request: Request, ctx: AppContextDep
) -> dict[str, Any]:
    """Generated files (documents, decks, spreadsheets, …) produced while working the task.

    Aggregates workspace artifacts across the task's linked sessions and dedupes
    to the newest record per workspace file, so a file regenerated in a later
    session surfaces once at its latest state. For a routine the rollup also
    covers its promoted occurrences — the routine itself never runs, so its
    files are always produced by an occurrence's sessions.
    """
    actor = request_actor(request, ctx.auth_store)
    task = get_task_for_actor(ctx.task_store, task_id, actor, record_view=True)
    sources: list[tuple[str, str]] = [
        (task_id, session_id) for session_id in task.get("linkedSessionIds", [])
    ]
    for occurrence in occurrence_file_records(ctx, task, actor):
        sources.extend(
            (occurrence["id"], session_id)
            for session_id in occurrence.get("linkedSessionIds", [])
        )
    ordered = sorted(
        newest_artifacts_by_file(
            ctx, sources, owner_user_id=actor["userId"], all_versions=request.query_params.get("versions") == "all"
        ).values(),
        key=lambda item: item.get("createdAt") or "",
        reverse=True,
    )
    return {"taskId": task_id, "artifacts": ordered}
