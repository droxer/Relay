"""Workspace-file artifact identity and the newest-per-file index rule.

The thread artifact routes and the session store's ``workspace_files``
projection both key files through ``workspace_file_key``.
"""

from __future__ import annotations

from pathlib import PurePosixPath
from typing import Any

from .workspace_layout import THREAD_RECORDS_DIRS


def is_thread_record_artifact(session: dict[str, Any], artifact: dict[str, Any]) -> bool:
    """Recognize continuity files by their workspace path, never their title.

    Older records may carry only an absolute path; resolve it relative to the
    recorded workspace without consulting the backend's filesystem.
    """
    relative = artifact.get("workspaceRelativePath")
    if not isinstance(relative, str) or not relative:
        path = artifact.get("path")
        if not isinstance(path, str):
            return False
        relative = path.replace("\\", "/")
        workspace = session.get("workspacePath")
        if isinstance(workspace, str) and workspace:
            prefix = workspace.replace("\\", "/").rstrip("/") + "/"
            if relative.startswith(prefix):
                relative = relative[len(prefix):]
    parts = PurePosixPath(relative.replace("\\", "/")).parts
    for directory in THREAD_RECORDS_DIRS:
        root = PurePosixPath(directory).parts
        if parts[:len(root)] == root and len(parts) == len(root) + 2:
            return parts[-1] in ("HANDOFF.md", "HANDOFF.json")
    return False


def workspace_file_key(artifact: dict[str, Any]) -> str | None:
    """The file identity the artifact index dedupes on."""
    for key in ("workspaceRelativePath", "path", "id"):
        value = artifact.get(key)
        if isinstance(value, str) and value:
            return value
    return None


def is_workspace_artifact(artifact: dict[str, Any]) -> bool:
    return artifact.get("kind") == "workspace_file"


def workspace_artifact_key(session: dict[str, Any], artifact: dict[str, Any]) -> str:
    return f"{session.get('workspacePath') or ''}::{workspace_file_key(artifact)}"


def workspace_artifacts(session: dict[str, Any]) -> list[dict[str, Any]]:
    """Generated-file artifacts for a session, newest record per file.

    A file re-generated by a later run gets a fresh artifact per change; the
    index and counts should surface each file once, at its latest state.
    """
    newest: dict[str | None, dict[str, Any]] = {}
    for artifact in session.get("artifacts", []):
        if not is_workspace_artifact(artifact):
            continue
        # Artifacts with no identity share the ``None`` slot, as before.
        key: str | None = workspace_file_key(artifact)
        current = newest.get(key)
        if current is None or (artifact.get("createdAt") or "") >= (
            current.get("createdAt") or ""
        ):
            newest[key] = artifact
    return list(newest.values())


def artifact_index_item(
    session: dict[str, Any], artifact: dict[str, Any]
) -> dict[str, Any]:
    return {
        **artifact,
        "sessionId": session["id"],
        "sessionTitle": session.get("title"),
        "taskGoal": session.get("taskGoal"),
        "ownerUserId": session.get("ownerUserId"),
        "workspacePath": session.get("workspacePath"),
        "sessionUpdatedAt": session.get("updatedAt"),
    }
